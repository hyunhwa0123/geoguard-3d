CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS restricted_zone (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL UNIQUE,
    boundary        geometry(Polygon, 4326) NOT NULL,
    min_altitude    DOUBLE PRECISION NOT NULL,
    max_altitude    DOUBLE PRECISION NOT NULL,
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT restricted_zone_altitude_range CHECK (min_altitude >= 0 AND max_altitude > min_altitude),
    CONSTRAINT restricted_zone_boundary_valid CHECK (ST_IsValid(boundary) AND NOT ST_IsEmpty(boundary))
);

CREATE TABLE IF NOT EXISTS telemetry (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drone_id        VARCHAR(64) NOT NULL,
    recorded_at     TIMESTAMPTZ NOT NULL,
    position        geometry(PointZ, 4326) NOT NULL,
    altitude        DOUBLE PRECISION NOT NULL,
    heading         DOUBLE PRECISION,
    speed           DOUBLE PRECISION,
    status          VARCHAR(16) NOT NULL DEFAULT 'SAFE',
    received_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT telemetry_altitude_range CHECK (altitude BETWEEN -500 AND 20000),
    CONSTRAINT telemetry_heading_range CHECK (heading IS NULL OR heading >= 0 AND heading < 360),
    CONSTRAINT telemetry_speed_nonnegative CHECK (speed IS NULL OR speed >= 0),
    CONSTRAINT telemetry_status_values CHECK (status IN ('SAFE', 'WARNING', 'DANGER'))
);

CREATE TABLE IF NOT EXISTS risk_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telemetry_id    BIGINT NOT NULL REFERENCES telemetry(id) ON DELETE CASCADE,
    zone_id         BIGINT REFERENCES restricted_zone(id) ON DELETE SET NULL,
    drone_id        VARCHAR(64) NOT NULL,
    status          VARCHAR(16) NOT NULL,
    distance_meters DOUBLE PRECISION NOT NULL,
    occurred_at     TIMESTAMPTZ NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT risk_event_warning_or_danger CHECK (status IN ('WARNING', 'DANGER')),
    CONSTRAINT risk_event_distance_nonnegative CHECK (distance_meters >= 0)
);

CREATE INDEX IF NOT EXISTS idx_restricted_zone_boundary_gist ON restricted_zone USING GIST (boundary);
CREATE INDEX IF NOT EXISTS idx_telemetry_position_gist ON telemetry USING GIST (position);
CREATE INDEX IF NOT EXISTS idx_telemetry_drone_recorded_at ON telemetry (drone_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_telemetry_recorded_at ON telemetry (recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_telemetry_danger_recorded_at ON telemetry (recorded_at DESC) WHERE status = 'DANGER';
CREATE INDEX IF NOT EXISTS idx_risk_event_drone_occurred_at ON risk_event (drone_id, occurred_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_risk_event_telemetry_id ON risk_event (telemetry_id);
